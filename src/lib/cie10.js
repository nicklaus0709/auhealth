const sinAcentos = (texto) => texto.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();

export function buscarCie10(texto, limite = 12) {
  const t = sinAcentos(texto.trim());
  if (!t) return CIE10_FRECUENTES.slice(0, limite);
  return CIE10_FRECUENTES.filter((c) => sinAcentos(c.codigo).startsWith(t) || sinAcentos(c.descripcion).includes(t)).slice(0, limite);
}
